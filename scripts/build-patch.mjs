/**
 * Regenerate cordis.patch.yml from the shipped web-app preset files.
 *
 * The preset override has to restate the complete `config` (the Loader
 * replaces it rather than merging), so the shipped plugin list is copied from
 * the running DSH checkout and only the two shell rows are changed. Re-run this
 * after upgrading DSH so the copied tool list tracks the shipped presets.
 *
 * Usage:
 *   node scripts/build-patch.mjs [DSH checkout root]
 *
 * Without an argument, DSH_CHECKOUT is used, then a sibling checkout such as
 * `../deepseek-harness`. The dev helper validates the directory before the
 * preset files are read.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { resolveCheckout } from './dev-paths.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const bundleRoot = resolve(here, '..')
const checkout = process.argv[2] === undefined ? resolveCheckout() : resolve(process.argv[2])

/** The two shipped rows replaced in each preset. */
const SHIPPED_ROWS = `          - id: tool-bash
            name: '@deepseek-ai/dsh-tool-bash'
            disabled: !!js process.platform === 'win32'
          - id: tool-pwsh
            name: '@deepseek-ai/dsh-tool-pwsh'
            disabled: !!js process.platform !== 'win32'`

/**
 * The replacement rows.
 *
 * `tool-bash` stays enabled outside Windows and disabled on Windows; the
 * Windows-only isolated group supplies its own `shell` service plus the
 * MinGW prompt section. `tool-pwsh` is disabled everywhere in these presets.
 */
const REPLACEMENT_ROWS = `          - id: tool-bash
            name: '@deepseek-ai/dsh-tool-bash'
            disabled: !!js process.platform === 'win32'
          - id: shell-mingw
            name: cordis:group
            group: true
            isolate:
              shell: true
            disabled: !!js process.platform !== 'win32'
            config:
              - id: mingw-shell
                name: '@local/dsh-win-mingw/executor'
              - id: mingw-tool-bash
                name: '@deepseek-ai/dsh-tool-bash'
              - id: mingw-shell-prompt
                name: '@local/dsh-win-mingw/prompt'
          - id: tool-pwsh
            name: '@deepseek-ai/dsh-tool-pwsh'
            disabled: true`

const PRESETS = [
  { rowId: 'preset-standard', file: 'standard.patch.yml' },
  { rowId: 'preset-ptc', file: 'ptc.patch.yml' },
  { rowId: 'preset-cordis', file: 'cordis.patch.yml' },
]

/** Extract the complete `config` body of one shipped preset declaration. */
function presetConfig(rowId, file) {
  const text = readFileSync(file, 'utf8')
  const lines = text.split(/\r?\n/u)
  const start = lines.findIndex(line => line === `        id: ${rowId.slice('preset-'.length)}`)
  if (start === -1) throw new Error(`${file}: cannot find the config for ${rowId}`)
  return lines.slice(start).join('\n').replace(/\s+$/u, '')
}

/** Rewrite the two shell rows and de-indent the config to top-level patch indentation. */
function rewrite(configText, file) {
  const occurrences = configText.split(SHIPPED_ROWS).length - 1
  if (occurrences !== 1) {
    throw new Error(`${file}: expected exactly one shipped shell row block, found ${occurrences}`)
  }
  const replaced = configText.replace(SHIPPED_ROWS, REPLACEMENT_ROWS)
  return replaced
    .split(/\r?\n/u)
    .map(line => line.startsWith('    ') ? line.slice(4) : line)
    .join('\n')
}

const header = `# MinGW shell preset overrides.
#
# Generated by scripts/build-patch.mjs from the @deepseek-ai/dsh-web-app preset
# files. Each override restates the complete shipped preset config because the
# Loader replaces a row's whole config; only the shell rows differ.
#
# On Windows, the marked group isolates the \`shell\` service, mounts the MinGW
# executor, the shipped bash tool, and the MinGW prompt section. On other
# platforms the group is disabled and the shipped bash tool keeps using the
# host bash executor. \`minimal\` (persistent pwsh) is intentionally unchanged.
`

const blocks = PRESETS.map(({ rowId, file }) => {
  const path = join(checkout, 'packages/bundle/web-app/presets', file)
  const config = rewrite(presetConfig(rowId, path), path)
  return `- id: ${rowId}
  name: '@deepseek-ai/dsh-agent-preset'
  config:
${config}`
})

const output = `${header}\n${blocks.join('\n\n')}\n`
writeFileSync(join(bundleRoot, 'cordis.patch.yml'), output)
console.log(`wrote ${join(bundleRoot, 'cordis.patch.yml')} from ${checkout}`)
